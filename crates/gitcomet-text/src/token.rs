/// What a syntax highlighter classified a span of text as. Themes map each kind
/// to a style; `None` is plain text.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub enum SyntaxTokenKind {
    None,
    Comment,
    CommentDoc,
    String,
    StringEscape,
    StringRegex,
    StringSpecial,
    Keyword,
    KeywordControl,
    Preproc,
    Number,
    Boolean,
    Function,
    FunctionMethod,
    FunctionSpecial,
    Constructor,
    Type,
    TypeBuiltin,
    TypeInterface,
    Namespace,
    Variable,
    VariableParameter,
    VariableSpecial,
    VariableBuiltin,
    Property,
    Label,
    Constant,
    ConstantBuiltin,
    Operator,
    Punctuation,
    PunctuationBracket,
    PunctuationDelimiter,
    PunctuationSpecial,
    PunctuationListMarker,
    Tag,
    Attribute,
    MarkupHeading,
    MarkupLink,
    TextLiteral,
    DiffPlus,
    DiffMinus,
    DiffDelta,
    Lifetime,
}

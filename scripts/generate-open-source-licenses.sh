#!/usr/bin/env bash
set -euo pipefail

# Regenerates crates/gitcomet-ui-gpui/assets/open_source_licenses.tsv from
# Cargo.lock. With --check, fails instead when the committed file is stale.

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_FILE="$ROOT_DIR/crates/gitcomet-ui-gpui/assets/open_source_licenses.tsv"
METADATA_FILE="$(mktemp)"
GENERATED_FILE="$(mktemp)"

case "${1-}" in
  "") check=0 ;;
  --check) check=1 ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

# Bundled assets that are not crates at all. These head the file, ahead of the
# dependency list.
BUNDLED_ASSET_LICENSE_ROWS=(
  $'Fira Code\t6.2-103-ge50b177\tSIL OFL-1.1'
  $'IBM Plex Sans\t3.005\tSIL OFL-1.1'
  $'Noto Emoji\t3.002\tSIL OFL-1.1'
  $'Lilex\t2.621\tSIL OFL-1.1'
  $'Catppuccin for VSCode (theme colors)\t3.19.0\tMIT'
  $'Eldritch (theme colors)\tc14f4df\tMIT'
  $'GitHub VS Code Theme (theme colors)\t6.3.5\tMIT'
  $'Gruvbox Theme (theme colors)\t1.29.1\tMIT'
  $'Night Owl (theme colors)\t2.1.1\tMIT'
  $'Nord Visual Studio Code (theme colors)\t0.19.0\tMIT'
  $'One Dark Pro (theme colors)\t3.20.2\tMIT'
  $'t3code (Grove, Ocean, Ember, Iris, T3 Chat palettes)\t0.0.45-nightly.20260930\tMIT'
  $'Tokyo Night (theme colors)\t1.1.2\tMIT'
  $'Visual Studio Code Monokai and Solarized themes\t1.105.1\tMIT'
  $'gpui-component (Rust, HTML, JavaScript and TypeScript highlight queries)\tmain, 2026-01\tApache-2.0'
  $'nvim-treesitter (Elm, Apex, Common Lisp and LaTeX highlights, Go injections)\tca581c3 (Elm, Apex, Common Lisp), 692b051 (LaTeX), master (Go)\tApache-2.0'
)

# Crates whose manifest names a licence file instead of an SPDX id, keyed by
# name@version so an upgrade has to confirm the licence again.
LICENSE_OVERRIDES='{
  "tree-sitter-newick@1.1.0": "CECILL-C",
  "wgsl-rs@0.1.0": "MIT",
  "wgsl-rs-ir@0.1.0": "MIT",
  "wgsl-rs-macros@0.1.0": "MIT"
}'

cleanup() {
  rm -f "$METADATA_FILE" "$GENERATED_FILE"
}
trap cleanup EXIT

cargo metadata --format-version 1 --locked > "$METADATA_FILE"

# An override for a crate that is gone, or that now declares its own licence,
# would hide the next change to it.
stale_overrides="$(jq -r --argjson overrides "$LICENSE_OVERRIDES" '
  (.packages | map({key: (.name + "@" + .version), value: .license}) | from_entries) as $declared
  | $overrides | keys[]
  | . as $key
  | select(($declared | has($key) | not) or $declared[$key] != null)
' "$METADATA_FILE")"
if [[ -n "$stale_overrides" ]]; then
  echo "error: no licence-less package matches these LICENSE_OVERRIDES entries:" >&2
  echo "$stale_overrides" >&2
  exit 1
fi

{
  echo "# Generated by scripts/generate-open-source-licenses.sh"
  printf '%s\n' "${BUNDLED_ASSET_LICENSE_ROWS[@]}"
  # Registry crates have a `source`; vendored path dependencies do not, so they
  # are picked out by manifest location instead. Reading them from the same
  # `cargo metadata` as everything else means their name, version and licence
  # come from their own Cargo.toml and cannot drift out of this file. The
  # workspace's own AGPL crates are path dependencies too, and are excluded by
  # the same test. Provenance for each vendored crate is in its Cargo.toml.
  jq -r --arg vendor_dir "$ROOT_DIR/vendor/" --argjson overrides "$LICENSE_OVERRIDES" '
    .packages
    | map(select(.source != null or (.manifest_path | startswith($vendor_dir))))
    | sort_by(.name, .version)
    | .[]
    | (.name + "@" + .version) as $key
    | [
        .name,
        .version,
        (.license // $overrides[$key]
          // error("\($key) declares no SPDX licence; add it to LICENSE_OVERRIDES in scripts/generate-open-source-licenses.sh"))
      ]
    | @tsv
  ' "$METADATA_FILE"
} > "$GENERATED_FILE"

if [[ $check -eq 1 ]]; then
  if ! diff -u "$OUT_FILE" "$GENERATED_FILE"; then
    echo "error: $OUT_FILE is stale; run scripts/generate-open-source-licenses.sh" >&2
    exit 1
  fi
  echo "ok   $OUT_FILE matches Cargo.lock"
  exit 0
fi

cp "$GENERATED_FILE" "$OUT_FILE"
echo "Wrote $(wc -l < "$OUT_FILE") lines to $OUT_FILE"
